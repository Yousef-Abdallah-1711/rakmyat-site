export function getLocalizedPath(locale: Locale, currentPath: string) {
  const segments = currentPath.split("/").filter(Boolean);
  const routeSegments = segments[0] === "en" || segments[0] === "ar"
    ? segments.slice(1)
    : segments;
  return `/${locale}${routeSegments.length ? `/${routeSegments.join("/")}` : ""}`;
}
